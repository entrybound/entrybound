#!/usr/bin/env python3
"""Generate EXP-CODEC-001 ebr specs (stdlib only, deterministic).

Writes spec-screen.yaml (Stage A, tuning only) and spec.yaml (Stage B, tuning).
Validation-look specs are derived from spec.yaml at look time (splits: [validation],
candidates restricted to W and S) and committed plus registered before the run.

Usage: C:/Python313/python.exe research/experiments/EXP-CODEC-001/make_specs.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_WSL = "/mnt/d/Projects/entrybound/entrybound"
EXP = "EXP-CODEC-001"
BIN = "/root/eb-research/target/harness/release"
DECISIONS = ["DEC-CMP-008", "DEC-CMP-009", "DEC-CMP-045"]
PROFILES = ["fast", "balanced", "dense", "extreme"]

# Portfolio applicability per profile (protocol section 5.2). same_as aliases are not run twice.
PORTFOLIO_PROFILES = {
    "B_SQ": PROFILES, "B_STORE": PROFILES, "B_ZSTD": PROFILES, "B_ZSTD_LZ4": PROFILES,
    "B_ZSTD_LZMA2": ["dense", "extreme"], "B_DEFLATE_ZSTD": PROFILES, "B_DEFLATE": PROFILES,
    "E_LZMA2_XZ": ["dense", "extreme"], "E_BROTLI": ["dense", "extreme"], "E_BZIP2": ["dense", "extreme"],
    "E_PPMD": ["dense", "extreme"], "E_BSC": ["dense", "extreme"], "E_CM": ["extreme"],
    "E_FLAC": ["dense", "extreme"], "E_SCI": ["dense", "extreme"], "E_OPENZL": ["dense", "extreme"],
    "W_PER_PROFILE": ["fast", "balanced"], "W_LDM": ["dense", "extreme"], "W_CHUNK": ["fast", "balanced", "extreme"],
}


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def header(stage: str, question: str, hypothesis: str, exp_id: str = EXP) -> list[str]:
    return [
        "schema: ebr.spec.v1",
        f"experiment_id: {exp_id}",
        "status: pre-registration-draft (gate G-A pending; protocol.md section 1)",
        f"notes: {q('Generated by make_specs.py. ' + stage + ' Flags marked TOOLING in protocol.md section 7.2 do not exist yet; runs refuse until built (CC-1).')}",
        f"question: {q(question)}",
        f"hypothesis: {q(hypothesis)}",
        "decision_ids: [" + ", ".join(DECISIONS) + "]",
    ]


def common_tail(timeout_s: int, report: list[str]) -> list[str]:
    return [
        "repetitions: 2",
        "warmups: 0",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        "timing: false",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
        f"  requires: [{BIN}/ebr-codec, {BIN}/ebr-planner]",
        f"  timeout_s: {timeout_s}",
        "analysis:",
        "  pairing: item",
        "  report_metrics: [" + ", ".join(report) + "]",
    ]


def screen_spec() -> str:
    lines = header(
        "Stage A (screen, tuning split only; exploratory, never decision evidence).",
        "At production chunk scope (balanced, extreme and fast-eligible chunking), what stored bytes, "
        "window, container and round-trip result does every configuration of configs/universe-stageA.json "
        "give on an object-preserving 64 MiB sample of every tuning item?",
        "Screen only. Configurations advance to Stage B under the mechanical rule of protocol.md section 12.1. "
        "Controls: external zstd at window_log 20 reproduces production zstd payloads byte for byte; every "
        "configuration round-trips (HC-02).",
        exp_id=f"{EXP}-screen",
    )
    lines += ["candidates:"]
    for prof in ["fast", "balanced", "extreme"]:
        subset = "fast-eligible" if prof == "fast" else "all"
        lines += [f"  - name: screen-{prof}", f"    params: {{profile: {prof}, subset: {subset}}}"]
    lines += [
        "command: >-",
        f"  {BIN}/ebr-codec chunk-matrix --item-path {{item_path}} --experiment-id {EXP}-screen",
        "  --env-name wsl-ubuntu --profile {profile} --production-chunking object",
        f"  --universe {REPO_WSL}/research/experiments/{EXP}/configs/universe-stageA.json",
        "  --universe-subset {subset} --chunk-sample-bytes 67108864 --chunk-sample-seed 20260917",
        f"  --detail-out /root/eb-research/raw-detail/{EXP}/stageA/{{item_id}}/{{candidate}}-r{{rep}}.jsonl.gz",
        "  --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: input_bytes, source: input, family: size, direction: none, unit: B}",
        "  - {name: sampled_plaintext_bytes, source: stdout_json, key: payload.sampled_plaintext_bytes, family: size, direction: none, unit: B}",
        "  - {name: unique_chunk_count, source: stdout_json, key: payload.unique_chunk_count, family: other, direction: none, unit: count}",
        "  - {name: configurations_run, source: stdout_json, key: payload.configurations_run, family: other, direction: none, unit: count}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: window20_reconciliation_mismatches, source: stdout_json, key: payload.window20_reconciliation_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: matrix_digest_sha256, source: stdout_json, key: payload.matrix_digest_sha256, family: correctness, kind: string}",
        "  - {name: detail_sha256, source: stdout_json, key: payload.detail_sha256, family: correctness, kind: string}",
        "  - {name: max_rss_bytes, source: resource, family: memory_peak, direction: minimize, unit: B}",
        "  - {name: wall_s, source: resource, family: time_wall, direction: minimize, unit: s}",
    ]
    lines += common_tail(21600, ["sampled_plaintext_bytes", "roundtrip_mismatches", "window20_reconciliation_mismatches"])
    return "\n".join(lines) + "\n"


def stage_b_spec() -> str:
    lines = header(
        "Stage B (exact portfolio cost), tuning split. Universe = configs/universe-stageB.json written by screen.py.",
        "At production chunk scope with exact-chunk dedup, what artifact_bytes does each pre-registered codec "
        "portfolio (baseline sets, extended additions, Zstandard window policies) need on every "
        "tuning item under the production v4 qualification rule?",
        "H1a-H1e of protocol.md section 3 (for example LZMA2 in the baseline is distinguishable but below the "
        "section 7.3 baseline-codec minimum gain at corpus level; LZ4 adds no size; windows above log 20 are "
        "equivalent for independent chunks). Controls: PCM equals real encodes for production-expressible "
        "portfolios; zero round-trip mismatches.",
    )
    lines += ["candidates:"]
    for port, profs in PORTFOLIO_PROFILES.items():
        for prof in profs:
            name = f"{port.lower().replace('_', '-')}-{prof}"
            lines += [f"  - name: {name}", f"    params: {{portfolio: {port}, profile: {prof}}}"]
    lines += [
        "command: >-",
        f"  {BIN}/ebr-planner portfolio --item-path {{item_path}} --experiment-id {EXP}",
        "  --env-name wsl-ubuntu --profile {profile} --portfolio {portfolio}",
        f"  --portfolios {REPO_WSL}/research/experiments/{EXP}/configs/portfolios.json",
        f"  --universe {REPO_WSL}/research/experiments/{EXP}/configs/universe-stageB.json",
        f"  --plan-record-model {REPO_WSL}/research/experiments/{EXP}/configs/plan-record-model.json",
        "  --selection-rule production-v4 --reconcile-expressible true",
        f"  --matrix-cache /root/eb-research/cache/{EXP}/stageB/{{item_id}}-{{profile}}-r{{rep}}.jsonl.gz",
        f"  --detail-out /root/eb-research/raw-detail/{EXP}/stageB/{{item_id}}/{{candidate}}-r{{rep}}.jsonl.gz",
        "  --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: input_bytes, source: input, family: size, direction: none, unit: B}",
        "  - {name: artifact_bytes, source: stdout_json, key: payload.artifact_bytes, family: size, direction: minimize, unit: B}",
        "  - {name: artifact_bytes_is_exact, source: stdout_json, key: payload.artifact_bytes_is_exact, family: correctness, direction: none, unit: bool}",
        "  - {name: pcm_reconciliation_mismatches, source: stdout_json, key: payload.pcm_reconciliation_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: metadata_bytes, source: stdout_json, key: payload.byte_accounting.metadata_bytes, family: size, direction: minimize, unit: B}",
        "  - {name: index_bytes, source: stdout_json, key: payload.byte_accounting.index_bytes, family: size, direction: minimize, unit: B}",
        "  - {name: chunk_payload_bytes, source: stdout_json, key: payload.chunk_payload_bytes, family: size, direction: minimize, unit: B}",
        "  - {name: plan_record_bytes, source: stdout_json, key: payload.plan_record_bytes, family: size, direction: minimize, unit: B}",
        "  - {name: store_fallback_plaintext_fraction, source: stdout_json, key: payload.store_fallback_plaintext_fraction, family: other, direction: none, unit: fraction}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: portfolio_digest_sha256, source: stdout_json, key: payload.portfolio_digest_sha256, family: correctness, kind: string}",
        "  - {name: ratio, source: derived, op: ratio, args: [artifact_bytes, input_bytes], family: size, direction: minimize}",
        "  - {name: max_rss_bytes, source: resource, family: memory_peak, direction: minimize, unit: B}",
        "  - {name: wall_s, source: resource, family: time_wall, direction: minimize, unit: s}",
    ]
    tail = common_tail(172800, ["artifact_bytes", "ratio", "pcm_reconciliation_mismatches", "roundtrip_mismatches"])
    tail.insert(tail.index("analysis:") + 1, "  baseline: b-sq-balanced")
    lines += tail
    return "\n".join(lines) + "\n"


def main() -> None:
    (HERE / "spec-screen.yaml").write_text(screen_spec(), encoding="utf-8", newline="\n")
    (HERE / "spec.yaml").write_text(stage_b_spec(), encoding="utf-8", newline="\n")
    print(json.dumps({"written": ["spec-screen.yaml", "spec.yaml"], "stage_b_candidates": sum(len(v) for v in PORTFOLIO_PROFILES.values())}))


if __name__ == "__main__":
    main()
