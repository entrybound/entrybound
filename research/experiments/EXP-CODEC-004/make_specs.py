#!/usr/bin/env python3
"""Generate EXP-CODEC-004 specs (stdlib only, deterministic).

spec-screen.yaml  Stage A transform screen (tuning, 64 MiB object-preserving sample).
spec.yaml         Stage B exact: DEC-CMP-043 transform sets under their applicability rule, always-try and none (tuning).
spec-adversarial.yaml  MVT-06(d) applicability-rule CPU-per-byte scaling series on generated adversarial inputs.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_WSL = "/mnt/d/Projects/entrybound/entrybound"
EXP = "EXP-CODEC-004"
BIN = "/root/eb-research/target/harness/release"
CFG = f"{REPO_WSL}/research/experiments/{EXP}/configs"
PROFILES = ["balanced", "dense", "extreme"]
TSETS = ["sq", "bcj", "delta", "float", "stream", "multi", "none"]
RULES = ["rule", "always-try", "none"]
ADV_RULES = ["frozen-probe", "architecture-signature", "dtype-signature"]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def tail(timing: bool, timeout: int, report: list[str], baseline: str | None, reps: int) -> list[str]:
    out = [
        f"repetitions: {reps}",
        "warmups: 0",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        f"timing: {'true' if timing else 'false'}",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
    ]
    if timing:
        out += ["  cpu_affinity: [2]"]
    out += [f"  requires: [{BIN}/ebr-codec, {BIN}/ebr-planner]", f"  timeout_s: {timeout}"]
    if timing:
        out += ["guard:", "  max_loadavg_1m: 2.0", "  max_other_cpu_percent: 3.0", "  max_wait_s: 300"]
    out += ["analysis:"]
    if baseline:
        out += [f"  baseline: {baseline}"]
    out += ["  pairing: item", "  report_metrics: [" + ", ".join(report) + "]"]
    return out


def head(exp_id: str, note: str, question: str, hypothesis: str, decisions: list[str]) -> list[str]:
    return [
        "schema: ebr.spec.v1",
        f"experiment_id: {exp_id}",
        "status: pre-registration-draft (gate G-A pending)",
        f"notes: {q(note)}",
        f"question: {q(question)}",
        f"hypothesis: {q(hypothesis)}",
        "decision_ids: [" + ", ".join(decisions) + "]",
        "candidates:",
    ]


def screen() -> str:
    lines = head(f"{EXP}-screen",
                 "Generated by make_specs.py. Stage A, exploratory. transform-matrix is TOOLING (protocol 7.1).",
                 "Ahead of the Stage A reference codecs, which transform configurations of configs/transform-universe.json reduce stored bytes on production chunks of an object-preserving 64 MiB sample of every tuning item?",
                 "Screen only (protocol 12.1). Controls: delta-distance(1) equals delta8/v1 and byte-plane-split(2,4,8) equals byte-shuffle/v1 byte for byte; every transform round-trips.",
                 ["DEC-CMP-043"])
    for p in ["dense", "extreme"]:
        lines += [f"  - name: tscreen-{p}", f"    params: {{profile: {p}}}"]
    lines += [
        "command: >-",
        f"  {BIN}/ebr-codec transform-matrix --item-path {{item_path}} --experiment-id {EXP}-screen",
        "  --env-name wsl-ubuntu --profile {profile} --production-chunking object",
        f"  --universe {CFG}/transform-universe.json --codecs stage_a",
        "  --chunk-sample-bytes 67108864 --chunk-sample-seed 20260917 --record-applicability-inputs true",
        f"  --detail-out /root/eb-research/raw-detail/{EXP}/stageA/{{item_id}}/{{candidate}}-r{{rep}}.jsonl.gz --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: sampled_plaintext_bytes, source: stdout_json, key: payload.sampled_plaintext_bytes, family: size, direction: none, unit: B}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: identity_control_mismatches, source: stdout_json, key: payload.identity_control_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: matrix_digest_sha256, source: stdout_json, key: payload.matrix_digest_sha256, family: correctness, kind: string}",
        "  - {name: detail_sha256, source: stdout_json, key: payload.detail_sha256, family: correctness, kind: string}",
        "  - {name: max_rss_bytes, source: resource, family: memory_peak, direction: minimize, unit: B}",
    ]
    lines += tail(False, 21600, ["roundtrip_mismatches", "identity_control_mismatches"], None, 2)
    return "\n".join(lines) + "\n"


def stage_b() -> str:
    lines = head(EXP,
                 "Generated by make_specs.py. Stage B exact portfolio cost with transforms (tuning). Candidates: DEC-CMP-043 transform sets under their own applicability rule (configs/applicability.json), plus always-try and none sensitivity arms for the new families.",
                 "At production chunk scope, what artifact_bytes, trial-encode counts, selection losses and missed savings does each structural-transform set produce per profile on every tuning item under its applicability rule, always-try and none?",
                 "H1a-H1f of protocol.md section 3 (architecture-matched BCJ clears the transform band on F09; float/byte-plane beat byte-shuffle on F07 floats; signature applicability matches always-try within one band unit with at least 50% fewer trials; always-try fails the non-target encode_wall_s condition).",
                 ["DEC-CMP-043"])
