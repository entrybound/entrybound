#!/usr/bin/env python3
"""Generate EXP-CODEC-003 specs (stdlib only, deterministic).

spec.yaml: allocator-exact decode memory per codec configuration (tuning split).
Survivor configurations of EXP-CODEC-001/004 are appended by the same mechanical
rule as EXP-CODEC-002 (make_candidates.py, tooling) before any run.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = "EXP-CODEC-003"
BIN = "/root/eb-research/target/harness-alloc/release/ebr-codec"
DECISIONS = ["DEC-CMP-045", "DEC-CMP-008", "DEC-CMP-009", "DEC-CMP-043", "DEC-CON-004"]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def benign_candidates() -> list[tuple[str, str, str]]:
    out = [("store-prod", "store(production)", "balanced")]
    for lvl, prof in [(1, "fast"), (3, "balanced"), (5, "balanced"), (9, "dense"), (15, "dense"), (19, "extreme"), (22, "extreme")]:
        out.append((f"zstd-prod-l{lvl}", f"zstd(production,level={lvl})", prof))
    out.append(("lz4-prod", "lz4(production)", "balanced"))
    for preset, d, prof in [(4, 1048576, "dense"), (6, 4194304, "dense"), (9, 8388608, "extreme")]:
        out.append((f"lzma2-prod-p{preset}", f"lzma2(production,preset={preset},dict={d})", prof))
    for w in (17, 19, 21, 23, 24, 27):
        out.append((f"zstd-ext-l19-w{w}", f"zstd-window(external,level=19,window_log={w},ldm=off)", "fast"))
    for w in (24, 27):
        out.append((f"zstd-ldm-l19-w{w}", f"zstd-ldm(external,level=19,window_log={w})", "fast"))
    for lvl in (3, 15):
        out.append((f"zstd-delta8-l{lvl}", f"zstd+delta8(production,level={lvl})", "dense"))
        out.append((f"zstd-shuffle4-l{lvl}", f"zstd+byte-shuffle-4(production,level={lvl})", "dense"))
    for lbl, name in [("brotli(external,quality=11,lgwin=24)", "brotli-q11-w24"),
                      ("brotli-large-window(external,quality=11,lgwin=30)", "brotli-lw30"),
                      ("bzip2(external,level=9)", "bzip2-9"),
                      ("ppmd7(external,7zip-level=5)", "ppmd-l5"), ("ppmd7(external,7zip-level=9)", "ppmd-l9"),
                      ("bsc(external,bwt,qlfc-adaptive)", "bsc-adaptive"),
                      ("cm-zpaq(external,-m5)", "cm-zpaq-m5")]:
        out.append((name, lbl, "extreme"))
    return out


def benign_spec() -> str:
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}",
        "status: pre-registration-draft (gate G-A pending; counting allocator and bound H are decision-method 14 item 17)",
        f"notes: {q('Generated by make_specs.py. Binary built with the ebr-alloc counting allocator feature into target/harness-alloc (TOOLING, protocol 7.1). One configuration per process.')}",
        f"question: {q('For each decode configuration, what is the exact allocator peak above R0_max, how is it attributed (state, output, transform intermediate, other), and how tight is each candidate definition of the declared decode requirement?')}",
        f"hypothesis: {q('H1a-H1f of protocol.md section 3: zstd window-20 decode exceeds the declared 4 MiB set only when output buffers are counted; LZMA2 stays within lzma2_get_memory_usage plus output; PPMd, brotli large-window and bsc decode memory is bounded by a declarable formula (H1d); window series equivalent for single-segment chunk frames (H1c). Binary oracle: bound_exceedances = 0 under each candidate definition that claims to be an upper bound.')}",
        "decision_ids: [" + ", ".join(DECISIONS) + "]",
        "candidates:",
    ]
    for name, label, prof in benign_candidates():
        lines += [f"  - name: {name}", f"    params: {{label: {q(label)}, chunk_profile: {prof}}}"]
    lines += [
        "command: >-",
        f"  {BIN} decode-memory --item-path {{item_path}} --experiment-id {EXP}",
        "  --env-name wsl-ubuntu --candidate-exact {label} --chunk-profile {chunk_profile}",
        "  --payload-sample 8 --payload-sample-seed 20260917 --r0-runs 20 --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: input_bytes, source: input, family: size, direction: none, unit: B}",
        "  - {name: r0_max_bytes, source: stdout_json, key: payload.r0_max_bytes, family: memory_peak, direction: none, unit: B}",
        "  - {name: alloc_peak_bytes, source: stdout_json, key: payload.alloc_peak_bytes, family: memory_peak, direction: minimize, unit: B}",
        "  - {name: alloc_peak_state_bytes, source: stdout_json, key: payload.attribution.state, family: memory_peak, direction: minimize, unit: B}",
        "  - {name: alloc_peak_output_bytes, source: stdout_json, key: payload.attribution.output, family: memory_peak, direction: minimize, unit: B}",
        "  - {name: declared_working_set_bytes, source: stdout_json, key: payload.declared_working_set_bytes, family: other, direction: none, unit: B}",
        "  - {name: declared_window_bytes, source: stdout_json, key: payload.declared_window_bytes, family: other, direction: none, unit: B}",
        "  - {name: declared_tightness_ratio, source: stdout_json, key: payload.declared_tightness_ratio.status_quo, family: other, direction: minimize, unit: ratio}",
        "  - {name: bound_exceedances, source: stdout_json, key: payload.bound_exceedances, family: correctness, direction: minimize, unit: count}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: attribution_digest_sha256, source: stdout_json, key: payload.attribution_digest_sha256, family: correctness, kind: string}",
        "  - {name: max_rss_bytes, source: resource, family: memory_peak, direction: minimize, unit: B}",
        "repetitions: 2",
        "warmups: 0",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        "timing: false",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
        f"  requires: [{BIN}]",
        "  timeout_s: 7200",
        "analysis:",
        "  baseline: zstd-prod-l3",
        "  pairing: item",
        "  report_metrics: [alloc_peak_bytes, declared_tightness_ratio, bound_exceedances]",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    (HERE / "spec.yaml").write_text(benign_spec(), encoding="utf-8", newline="\n")
    print(json.dumps({"benign_candidates": len(benign_candidates())}))


if __name__ == "__main__":
    main()
