#!/usr/bin/env python3
"""Generate EXP-CODEC-002 timing specs (stdlib only, deterministic).

spec.yaml (wsl-ubuntu, st-v {2}) and spec-windows.yaml (windows-host, st-p {2}) carry the
pre-registered minimum candidate set of protocol.md section 4. make_candidates.py (tooling)
appends EXP-CODEC-001/004 survivors mechanically before any timing run.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = "EXP-CODEC-002"
DECISIONS = ["DEC-CMP-008", "DEC-CMP-009", "DEC-CMP-045", "DEC-CMP-043", "DEC-CMP-007"]


def cands() -> list[tuple[str, str, str]]:
    """(name, label, batch_profile)."""
    out: list[tuple[str, str, str]] = []
    out.append(("store-prod", "store(production)", "balanced"))
    for lvl, prof in [(1, "fast"), (3, "balanced"), (5, "balanced"), (9, "dense"), (15, "dense"), (19, "extreme"), (22, "extreme")]:
        out.append((f"zstd-prod-l{lvl}", f"zstd(production,level={lvl})", prof))
    out.append(("lz4-prod", "lz4(production)", "balanced"))
    for preset, dict_b, prof in [(4, 1048576, "dense"), (6, 4194304, "dense"), (9, 8388608, "extreme")]:
        out.append((f"lzma2-prod-p{preset}", f"lzma2(production,preset={preset},dict={dict_b})", prof))
    for lvl, prof in [(3, "balanced"), (9, "dense"), (15, "extreme")]:
        out.append((f"zstd-delta8-l{lvl}", f"zstd+delta8(production,level={lvl})", prof))
        for w in (2, 4, 8):
            out.append((f"zstd-shuffle{w}-l{lvl}", f"zstd+byte-shuffle-{w}(production,level={lvl})", prof))
    for preset, dict_b, prof in [(6, 4194304, "dense"), (9, 8388608, "extreme")]:
        out.append((f"lzma2-delta8-p{preset}", f"lzma2+delta8(production,preset={preset},dict={dict_b})", prof))
        for w in (2, 4, 8):
            out.append((f"lzma2-shuffle{w}-p{preset}", f"lzma2+byte-shuffle-{w}(production,preset={preset},dict={dict_b})", prof))
    for lvl, prof in [(1, "fast"), (3, "balanced"), (19, "extreme")]:
        out.append((f"parity-zstd-ext-l{lvl}", f"zstd-window(external,level={lvl},window_log=20,ldm=off)", prof))
    out.append(("zstd-prod-l3-aa1", "zstd(production,level=3)", "balanced"))
    out.append(("zstd-prod-l3-aa2", "zstd(production,level=3)", "balanced"))
    for label, name, prof in [
        ("brotli(external,quality=11,lgwin=24)", "brotli-q11-w24", "extreme"),
        ("bzip2(external,level=9)", "bzip2-9", "extreme"),
        ("ppmd7(external,7zip-level=5)", "ppmd-l5", "extreme"),
        ("bsc(external,bwt,qlfc-adaptive)", "bsc-adaptive", "extreme"),
        ("zstd-window(external,level=19,window_log=23,ldm=off)", "zstd-ext-l19-w23", "fast"),
        ("zstd-window(external,level=19,window_log=27,ldm=off)", "zstd-ext-l19-w27", "fast"),
        ("zstd-ldm(external,level=19,window_log=24)", "zstd-ldm-l19-w24", "fast"),
        ("deflate(external,level=6)", "deflate-6", "balanced"),
    ]:
        out.append((name, label, prof))
    out.append(("liblz4-dec", "lz4-decode-backend(liblz4,payload=lz4(production))", "balanced"))
    out.append(("liblzma-dec-p6", "lzma2-decode-backend(liblzma,payload=lzma2(production,preset=6,dict=4194304))", "dense"))
    out.append(("liblzma-dec-p9", "lzma2-decode-backend(liblzma,payload=lzma2(production,preset=9,dict=8388608))", "extreme"))
    return out


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def spec(windows: bool) -> str:
    binpath = "D:/eb-research/target/harness/release/ebr-codec.exe" if windows else "/root/eb-research/target/harness/release/ebr-codec"
    cache = "D:/eb-research/cache/EXP-CODEC-002/batches" if windows else "/root/eb-research/cache/EXP-CODEC-002/batches"
    env = "windows-host" if windows else "wsl-ubuntu"
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}{'-windows' if windows else ''}",
        "status: pre-registration-draft (gate G-A pending; timing gated on decision-method 14 items 3 and 4)",
        f"notes: {q('Generated by make_specs.py. Minimum candidate set; make_candidates.py appends EXP-CODEC-001/004 survivors before any run. The bench subcommand and backend binaries are TOOLING (protocol 7.2). ' + ('Windows: st-p affinity {2}; st-e {18} report arm uses the same spec with cpu_affinity [18] and experiment_id suffix -ecore.' if windows else 'WSL: st-v affinity {2}; guard max_loadavg_1m = 1.0 + 1 thread.'))}",
        f"question: {q('What in-process encode/decode wall time, CPU time and throughput does each codec, transform and C-reference decoder configuration have on a fixed 8 MiB production-chunk batch per item, under pinned single-thread affinity?')}",
        f"hypothesis: {q('H1a-H1f of protocol.md section 3 (LZ4 decode clears the baseline-codec throughput band versus zstd-1; LZMA2 and PPMd decode are much slower than zstd-19; windows above log 20 are equivalent for independent chunks; structural inverses add under one band unit; C-reference decoders are within two band units and byte-identical). Controls: parity of production versus direct zstd decode, and A/A equivalence of duplicated candidates.')}",
        "decision_ids: [" + ", ".join(DECISIONS) + "]",
        "candidates:",
    ]
    for name, label, prof in cands():
        lines += [f"  - name: {name}", f"    params: {{label: {q(label)}, batch_profile: {prof}}}"]
    lines += [
        "command: >-",
        f"  {binpath} bench --item-path {{item_path}} --experiment-id {EXP}",
        f"  --env-name {env} --candidate-exact {{label}}",
        f"  --batch {cache}/{{item_id}}-{{batch_profile}}.ebrb --phase both --summary-stdout",
        f"shell: {'pwsh' if windows else 'bash'}",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: input_bytes, source: input, family: size, direction: none, unit: B}",
        "  - {name: batch_plaintext_bytes, source: stdout_json, key: payload.batch_plaintext_bytes, family: size, direction: none, unit: B}",
        "  - {name: encode_wall_s, source: stdout_json, key: payload.encode_wall_s, family: time_wall, direction: minimize, unit: s}",
        "  - {name: decode_wall_s, source: stdout_json, key: payload.decode_wall_s, family: time_wall, direction: minimize, unit: s}",
        "  - {name: encode_cpu_s, source: stdout_json, key: payload.encode_cpu_s, family: time_cpu, direction: minimize, unit: s}",
        "  - {name: decode_cpu_s, source: stdout_json, key: payload.decode_cpu_s, family: time_cpu, direction: minimize, unit: s}",
        "  - {name: encode_throughput_bps, source: stdout_json, key: payload.encode_throughput_bps, family: throughput, direction: maximize, unit: B/s}",
        "  - {name: decode_throughput_bps, source: stdout_json, key: payload.decode_throughput_bps, family: throughput, direction: maximize, unit: B/s}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: batch_sha256, source: stdout_json, key: payload.batch_sha256, family: correctness, kind: string}",
        "  - {name: payload_digest_sha256, source: stdout_json, key: payload.payload_digest_sha256, family: correctness, kind: string}",
        "  - {name: wall_s, source: resource, family: time_wall, direction: minimize, unit: s}",
        "repetitions: 30",
        "warmups: 2",
        "record_warmups: true",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        "timing: true",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        f"  os: [{'windows' if windows else 'linux'}]",
        "  arch: [x86_64]",
        "  emulated: false",
        "  cpu_affinity: [2]",
        f"  requires: [{binpath}]",
        "  timeout_s: 3600",
        "guard:",
    ]
    if not windows:
        lines += ["  max_loadavg_1m: 2.0"]
    lines += [
        "  max_other_cpu_percent: 3.0",
        "  sample_interval_s: 1.0",
        "  max_wait_s: 300",
        "analysis:",
        "  baseline: zstd-prod-l3",
        "  pairing: item_repetition",
        "  report_metrics: [encode_wall_s, decode_wall_s, decode_throughput_bps, roundtrip_mismatches]",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    (HERE / "spec.yaml").write_text(spec(False), encoding="utf-8", newline="\n")
    (HERE / "spec-windows.yaml").write_text(spec(True), encoding="utf-8", newline="\n")
    print(json.dumps({"candidates": len(cands())}))


if __name__ == "__main__":
    main()
