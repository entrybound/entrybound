#!/usr/bin/env python3
"""Generate the EXP-EVAL-001 specs: completion of the incumbent size/determinism/round-trip
pass (EXP-BASE-SIZE) over every tuning+validation item not already covered.

Pre-registered by research/experiments/EXP-EVAL-001/protocol.md. Deterministic: the same
manifest.json and the same EXP-BASE-SIZE coverage files always produce byte-identical specs.

Groups (protocol section "Corpus selectors"):
  small   remaining small items (not in EXP-BASE-SIZE-small coverage), all 28 configs, unsharded
          -> research/experiments/EXP-EVAL-001/spec.yaml  (experiment_id EXP-EVAL-001)
  medlo   remaining medium items with bytes <= SLOW_CAP_BYTES, all 28 configs, N shards
  medhi   remaining medium items with bytes >  SLOW_CAP_BYTES, 28 configs minus SLOW_CONFIGS
  large   all large items, LARGE_CONFIGS only
          -> research/experiments/EXP-EVAL-001/shards/EXP-EVAL-001-<group>-s<k>.yaml

Held-out items are never selected (run_baselines.select_items filters on split).

Run inside WSL with the research venv (PyYAML):
  cd /mnt/d/Projects/entrybound/entrybound
  PYTHONPATH=research/tools:research/baselines /root/eb-research/venv/bin/python \
      research/experiments/EXP-EVAL-001/make_specs.py [--shards 4]
"""
from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
RESEARCH = HERE.parents[1]
sys.path.insert(0, str(RESEARCH / "baselines"))

import run_baselines as rb  # noqa: E402

SEED = 20260917
SLOW_CAP_BYTES = 134_217_728  # 128 MiB
SLOW_CONFIGS = ["zpaq-m5", "tarbrotli-q11", "tarxz-9e"]
LARGE_CONFIGS = [
    "zip-9", "targz-gzip-6", "tarzstd-3-t1", "tarzstd-19-tN", "tarzstd-22-ultra-long27-t1",
    "tarxz-pixz", "tarlz4-1", "7z-mx9-solid", "7z-mx9-nosolid", "squashfs-zstd", "dwarfs-l7",
    "borg-repo", "restic-repo",
]
TIMEOUT_S = {"small": 1800.0, "medlo": 3600.0, "medhi": 7200.0, "large": 14400.0}
OLD_DETAIL = "research/raw/EXP-BASE-SIZE/roundtrip-detail.jsonl"


def covered(name: str) -> set:
    p = RESEARCH / "baselines" / "specs" / f"{name}.yaml.coverage.json"
    with open(p, encoding="utf-8") as f:
        return set(json.load(f)["item_ids"])


def shard(items, n):
    """Greedy balance by bytes: largest first onto the lightest shard (ties -> lowest index)."""
    bins = [[] for _ in range(n)]
    load = [0] * n
    for it in sorted(items, key=lambda x: (-x["bytes"], x["item_id"])):
        k = min(range(n), key=lambda i: (load[i], i))
        bins[k].append(it)
        load[k] += it["bytes"]
    return [sorted(b, key=lambda x: x["item_id"]) for b in bins if b]


def make(exp_id, configs, items, timeout_s):
    spec = rb.build_spec(configs, items, 2, timeout_s, SEED)
    spec["experiment_id"] = exp_id
    spec["status"] = "baselines-completion"
    spec["question"] = (
        "Completion of EXP-BASE-SIZE (research/experiments/EXP-EVAL-001/protocol.md): what artifact "
        "size, output determinism (2 repetitions, repeat-hash) and content round-trip does each pinned "
        "incumbent configuration achieve on the tuning+validation items not yet covered, timing disabled?"
    )
    spec["hypothesis"] = (
        "Descriptive incumbent-only pass (decision-method.md 0.1: not a decision experiment). "
        "Pre-registered expectations: every config except zpaq-m5 (drops symlinks) round-trips content "
        "on every item; single-threaded tar pipelines and 7z are byte-deterministic across repetitions; "
        "borg-repo and restic-repo are not (random repository keys/ids)."
    )
    spec["decision_ids"] = []
    detail = f"research/raw/{exp_id}/roundtrip-detail.jsonl"
    for m in spec["metrics"]:
        if m.get("source") == "check":
            m["command"] = m["command"].replace(OLD_DETAIL, detail)
    spec["raw_compression"] = "gzip"
    return spec


def dump(spec, path: Path, items, configs):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# GENERATED by research/experiments/EXP-EVAL-001/make_specs.py -- do not edit by hand.\n")
        yaml.safe_dump(spec, f, sort_keys=False, width=100)
    cov = {
        "experiment_id": spec["experiment_id"],
        "config_ids": configs,
        "item_count": len(items),
        "item_ids": [it["item_id"] for it in items],
        "item_bytes_total": sum(it["bytes"] for it in items),
        "samples": len(items) * len(configs) * 2,
    }
    with open(path.with_suffix(".coverage.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(cov, f, indent=2)
        f.write("\n")
    return cov


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--shards", type=int, default=4)
    args = ap.parse_args(argv)

    all_cfg = list(rb.CONFIGS)
    for c in SLOW_CONFIGS + LARGE_CONFIGS:
        if c not in rb.CONFIGS:
            raise SystemExit(f"unknown config {c}")
    small_done = covered("EXP-BASE-SIZE-small")
    med_done = covered("EXP-BASE-SIZE-medium-sample")
    splits = ["tuning", "validation"]
    small = [i for i in rb.select_items(["small"], splits, 0, None, SEED) if i["item_id"] not in small_done]
    medium = [i for i in rb.select_items(["medium"], splits, 0, None, SEED) if i["item_id"] not in med_done]
    large = rb.select_items(["large"], splits, 0, None, SEED)
    for it in small + medium + large:
        assert it["split"] in splits, it["item_id"]

    summary = []
    s = make("EXP-EVAL-001", all_cfg, small, TIMEOUT_S["small"])
    summary.append(dump(s, HERE / "spec.yaml", small, all_cfg))

    groups = [
        ("medlo", [i for i in medium if i["bytes"] <= SLOW_CAP_BYTES], all_cfg),
        ("medhi", [i for i in medium if i["bytes"] > SLOW_CAP_BYTES], [c for c in all_cfg if c not in SLOW_CONFIGS]),
        ("large", large, LARGE_CONFIGS),
    ]
    for g, items, cfgs in groups:
        for k, part in enumerate(shard(items, args.shards)):
            exp_id = f"EXP-EVAL-001-{g}-s{k}"
            spec = make(exp_id, cfgs, part, TIMEOUT_S[g])
            summary.append(dump(spec, HERE / "shards" / f"{exp_id}.yaml", part, cfgs))
    for c in summary:
        print(json.dumps({k: c[k] for k in ("experiment_id", "item_count", "item_bytes_total", "samples")}))


if __name__ == "__main__":
    main()
