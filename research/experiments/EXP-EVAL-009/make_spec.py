#!/usr/bin/env python3
"""Generate research/experiments/EXP-EVAL-009/spec.yaml: the clean-host re-execution subset
(10 small tuning items x 6 incumbent configs x 2 reps), a strict subset of cells already measured
by EXP-BASE-SIZE small (run size-small-20260917T033541Z), so deterministic columns can be diffed.

Run inside WSL with the research venv:
  cd /mnt/d/Projects/entrybound/entrybound
  PYTHONPATH=research/tools:research/baselines /root/eb-research/venv/bin/python research/experiments/EXP-EVAL-009/make_spec.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "baselines"))
import run_baselines as rb  # noqa: E402

ITEMS = [
    "f01-tuning-zstd-v1-5-7-git", "f02-tuning-lz4-intree-make-build", "f04-tuning-sourcelike",
    "f05-tuning-gutenberg-books", "f06-tuning-census-popest-2023", "f07-tuning-silesia-xray",
    "f08-tuning-chinook-sqlite", "f09-alpine-324-rootfs-binaries", "f12-tuning-nasa-ivl-photos-small",
    "f18-tuning-lz4-releases-1-9-to-1-10",
]
CONFIGS = ["zip-6", "targz-gzip-6", "tarzstd-19-t1", "tarxz-6", "7z-mx9-solid", "squashfs-zstd"]
OLD_DETAIL = "research/raw/EXP-BASE-SIZE/roundtrip-detail.jsonl"


def main():
    items = [it for it in rb.select_items(["small"], ["tuning"], 0, None, 20260917) if it["item_id"] in ITEMS]
    missing = sorted(set(ITEMS) - {it["item_id"] for it in items})
    if missing:
        raise SystemExit(f"items not found as small tuning items: {missing}")
    spec = rb.build_spec(CONFIGS, items, 2, 1800.0, 20260917)
    spec["experiment_id"] = "EXP-EVAL-009"
    spec["status"] = "reproducibility-drill"
    spec["question"] = (
        "Clean-host re-execution drill (research/experiments/EXP-EVAL-009/protocol.md, arm M2): do "
        "deterministic columns (artifact sha256, output bytes, roundtrip_ok) of 60 EXP-BASE-SIZE cells "
        "reproduce exactly on a freshly imported WSL distro provisioned only from committed definitions?"
    )
    spec["hypothesis"] = (
        "H2: every deterministic cell matches the original run, except cells whose tool version drifted "
        "(recorded from the clean host's tool-versions probe) or whose item has output_pin null."
    )
    spec["decision_ids"] = ["DEC-ECO-081"]
    for m in spec["metrics"]:
        if m.get("source") == "check":
            m["command"] = m["command"].replace(OLD_DETAIL, "research/raw/EXP-EVAL-009/roundtrip-detail.jsonl")
    with open(HERE / "spec.yaml", "w", encoding="utf-8", newline="\n") as f:
        f.write("# GENERATED by research/experiments/EXP-EVAL-009/make_spec.py -- do not edit by hand.\n")
        yaml.safe_dump(spec, f, sort_keys=False, width=100)
    print(f"wrote spec.yaml: {len(CONFIGS)} configs x {len(items)} items x 2 reps")


if __name__ == "__main__":
    main()
