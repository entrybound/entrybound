#!/usr/bin/env python3
"""Generate EXP-CODEC-008 specs (stdlib only, deterministic).

spec.yaml          export wrapper size ladder and seekable variants (tuning; deterministic).
spec-readers.yaml  reader acceptance / memory / parallel-decode census per variant (tuning; deterministic outcomes).
spec-timing.yaml   compress (in-process) timing of decision-relevant configurations (tuning small+medium; timing).
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
EXP = "EXP-CODEC-008"
BIN = "/root/eb-research/target/harness/release/ebr-codec"
TAR = "/root/eb-research/cache/EXP-CODEC-008/tar"
DEC = "decision_ids: [DEC-LEG-027, DEC-CMP-024]"

LADDER = (
    [("gzip", l, "none") for l in range(1, 10)]
    + [("zstd", l, "none") for l in (1, 3, 6, 9, 12, 15, 19, 22)]
    + [("xz", l, "none") for l in ("0", "3", "6", "9", "6e", "9e")]
    + [("bzip2", l, "none") for l in (1, 6, 9)]
    + [("zip", l, "none") for l in (1, 6, 9)]
)
VARIANTS = [
    ("gzip", 6, "members:8388608", "gzip-multimember-8m"),
    ("gzip", 6, "bgzf", "gzip-bgzf"),
    ("xz", "6", "blocks:8388608", "xz-multiblock-8m"),
    ("xz", "6", "blocks:67108864", "xz-multiblock-64m"),
    ("zstd", 9, "seekable:8388608", "zstd-seekable-8m"),
]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def tail(timing: bool, reps: int, baseline: str, report: list[str], requires: list[str], timeout: int) -> list[str]:
    out = [
        f"repetitions: {reps}",
        f"warmups: {2 if timing else 0}",
    ]
    if timing:
        out += ["record_warmups: true"]
    out += [
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        f"timing: {'true' if timing else 'false'}",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
    ]
    if timing:
        out += ["  cpu_affinity: [2]"]
    out += [f"  requires: [{', '.join(requires)}]", f"  timeout_s: {timeout}"]
    if timing:
        out += ["guard:", "  max_loadavg_1m: 2.0", "  max_other_cpu_percent: 3.0", "  max_wait_s: 300"]
    out += ["analysis:", f"  baseline: {baseline}", "  pairing: " + ("item_repetition" if timing else "item"),
            "  report_metrics: [" + ", ".join(report) + "]"]
    return out


def size_spec() -> str:
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}",
        "status: pre-registration-draft (gate G-A pending)",
        f"notes: {q('Generated by make_specs.py. Inputs: production tar/ZIP exports cached by prepare_exports.sh (SHA-256 recorded). export-ladder is TOOLING. Identity gate: frozen-parameter candidates must reproduce production ebound convert output byte for byte (frozen_identity_ok).')}",
        f"question: {q('What artifact_bytes does each export wrapper level and each seekable or multi-block variant produce on the production export of every tuning item, and do frozen parameters reproduce production bytes?')}",
        f"hypothesis: {q('H1a: xz 9 and zstd 19 are distinguishably smaller than the frozen xz 6 and zstd 9, gzip 9 is equivalent to gzip 6, zstd 3 is worse than zstd 9. Identity gate at frozen parameters must pass.')}",
        DEC,
        "candidates:",
    ]
    for w, l, extra in LADDER:
        name = f"{w}-l{l}"
        lines += [f"  - name: {name}", f"    params: {{wrapper: {w}, level: {q(str(l))}, variant: {q(extra)}}}"]
    for w, l, extra, name in VARIANTS:
        lines += [f"  - name: {name}", f"    params: {{wrapper: {w}, level: {q(str(l))}, variant: {q(extra)}}}"]
    lines += [
        "command: >-",
        f"  {BIN} export-ladder --tar {TAR}/{{item_id}}.tar --zip-source {TAR}/{{item_id}}.zipsrc",
        "  --wrapper {wrapper} --level {level} --variant {variant} --out {scratch}/export.bin",
        f"  --frozen-reference-dir {TAR}/frozen --experiment-id {EXP} --env-name wsl-ubuntu --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: input_bytes, source: stdout_json, key: payload.export_input_bytes, family: size, direction: none, unit: B}",
        "  - {name: artifact_bytes, source: path_size, path: '{scratch}/export.bin', family: size, direction: minimize, unit: B}",
        "  - {name: artifact_sha256, source: path_sha256, path: '{scratch}/export.bin', family: correctness}",
        "  - {name: frozen_identity_ok, source: stdout_json, key: payload.frozen_identity_ok, family: correctness, direction: maximize, unit: bool}",
        "  - {name: roundtrip_ok, source: stdout_json, key: payload.roundtrip_ok, family: correctness, direction: maximize, unit: bool}",
        "  - {name: ratio, source: derived, op: ratio, args: [artifact_bytes, input_bytes], family: size, direction: minimize}",
    ]
    lines += tail(False, 2, "gzip-l6", ["artifact_bytes", "ratio", "frozen_identity_ok"], [BIN], 172800)
    return "\n".join(lines) + "\n"


def readers_spec() -> str:
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}-readers",
        "status: pre-registration-draft (gate G-A pending)",
        f"notes: {q('Generated by make_specs.py. For each variant the command builds the variant (export-ladder) and runs every pinned reader via read_variant.sh under GNU time; outcomes are deterministic, memory per reader is from GNU time only (R1-16). Java readers run on the Windows host arm (identity_windows.ps1).')}",
        f"question: {q('Which pinned consumer readers accept each frozen, seekable and multi-block export variant, with what peak memory, and which decode in parallel?')}",
        f"hypothesis: {q('H1c-H1d: every reader accepts multi-member gzip, BGZF, multi-block xz and zstd seekable frames (export_acceptance_fraction = 1); xz 9 exports need more reader memory than xz 6 beyond the T-06 band.')}",
        DEC,
        "candidates:",
    ]
    base = [("gzip", 6, "none", "gzip-frozen"), ("zstd", 9, "none", "zstd-frozen"), ("xz", "6", "none", "xz-frozen"), ("xz", "9", "none", "xz-l9"),
            ("bzip2", 9, "none", "bzip2-frozen"), ("zip", 6, "none", "zip-frozen")]
    for w, l, extra, name in base + VARIANTS:
        lines += [f"  - name: {name}", f"    params: {{wrapper: {w}, level: {q(str(l))}, variant: {q(extra)}}}"]
    lines += [
        "command: >-",
        f"  {BIN} export-ladder --tar {TAR}/{{item_id}}.tar --zip-source {TAR}/{{item_id}}.zipsrc",
        "  --wrapper {wrapper} --level {level} --variant {variant} --out {scratch}/export.bin --summary-stdout >/dev/null &&",
        "  bash /mnt/d/Projects/entrybound/entrybound/research/experiments/EXP-CODEC-008/read_variant.sh",
        "  {scratch}/export.bin {wrapper} all --expect " + TAR + "/{item_id}.tar",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: readers, source: stdout_json, key: payload.readers, family: other, direction: none, unit: count}",
        "  - {name: export_acceptance_fraction, source: stdout_json, key: payload.export_acceptance_fraction, family: other, direction: maximize, unit: fraction}",
        "  - {name: peak_rss_bytes, source: stdout_json, key: payload.worst_reader_max_rss_bytes, family: memory_peak, direction: minimize, unit: B}",
        "  - {name: parallel_decode_readers, source: stdout_json, key: payload.parallel_decode_readers, family: other, direction: maximize, unit: count}",
        "  - {name: outcome_digest_sha256, source: stdout_json, key: payload.outcome_digest_sha256, family: correctness, kind: string}",
    ]
    lines += tail(False, 2, "gzip-frozen", ["export_acceptance_fraction", "peak_rss_bytes", "parallel_decode_readers"],
                  [BIN, "gzip", "pigz", "xz", "zstd", "bzip2", "7z", "bsdtar", "tar", "bgzip", "python3"], 172800)
    return "\n".join(lines) + "\n"


def timing_spec() -> str:
    m = json.loads((REPO / "research/corpus/manifest.json").read_text(encoding="utf-8"))
    ids = sorted(i["item_id"] for i in m["items"] if i["split"] == "tuning" and i["scale"] in ("small", "medium"))
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}-timing",
        "status: pre-registration-draft (gate G-A pending; timing gated on decision-method 14 items 3 and 4)",
        f"notes: {q('Generated by make_specs.py. In-process compress timing via export-ladder (production encoder crates) for the DEC-LEG-027 candidate parameter sets; the same invocation spawns the reference reader (gzip/zstd/xz/bzip2 -dc, unzip -p) and times it as a child process (T-04 process floor), emitting one JSON line. Tuning small+medium items; large-tier timing of status quo and max-ratio is spec-timing-large (derived mechanically, committed before any run).')}",
        f"question: {q('What compress wall/CPU time (in-process) and reader decode wall time do the DEC-LEG-027 candidate parameter sets cost per wrapper?')}",
        f"hypothesis: {q('H1b: zstd 19 is more than 10 T-03 band units slower to compress than zstd 9; xz 9 versus xz 6 differs by under 3 band units.')}",
        DEC,
        "candidates:",
    ]
    sets = [("gzip", 1), ("gzip", 6), ("gzip", 9), ("zstd", 1), ("zstd", 3), ("zstd", 9), ("zstd", 19), ("xz", "0"), ("xz", "6"), ("xz", "9"),
            ("bzip2", 1), ("bzip2", 9), ("zip", 1), ("zip", 6), ("zip", 9)]
    for w, l in sets:
        lines += [f"  - name: t-{w}-l{l}", f"    params: {{wrapper: {w}, level: {q(str(l))}}}"]
    lines += [
        "command: >-",
        f"  {BIN} export-ladder --tar {TAR}/{{item_id}}.tar --zip-source {TAR}/{{item_id}}.zipsrc",
        "  --wrapper {wrapper} --level {level} --variant none --timing-mode in-process --reference-reader-time true",
        "  --out {scratch}/export.bin --experiment-id EXP-CODEC-008-timing --env-name wsl-ubuntu --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "  item_ids:",
    ] + [f"    - {i}" for i in ids] + [
        "metrics:",
        "  - {name: encode_wall_s, source: stdout_json, key: payload.encode_wall_s, family: time_wall, direction: minimize, unit: s}",
        "  - {name: encode_cpu_s, source: stdout_json, key: payload.encode_cpu_s, family: time_cpu, direction: minimize, unit: s}",
        "  - {name: decode_wall_s, source: stdout_json, key: payload.reference_reader_decode_wall_s, family: time_wall, direction: minimize, unit: s}",
        "  - {name: artifact_sha256, source: path_sha256, path: '{scratch}/export.bin', family: correctness}",
    ]
    lines += tail(True, 20, "t-gzip-l6", ["encode_wall_s", "decode_wall_s"], [BIN, "gzip", "zstd", "xz", "bzip2", "unzip"], 21600)
    return "\n".join(lines) + "\n"


def main() -> None:
    (HERE / "spec.yaml").write_text(size_spec(), encoding="utf-8", newline="\n")
    (HERE / "spec-readers.yaml").write_text(readers_spec(), encoding="utf-8", newline="\n")
    (HERE / "spec-timing.yaml").write_text(timing_spec(), encoding="utf-8", newline="\n")
    print(json.dumps({"written": ["spec.yaml", "spec-readers.yaml", "spec-timing.yaml"], "ladder": len(LADDER), "variants": len(VARIANTS)}))


if __name__ == "__main__":
    main()
