#!/usr/bin/env python3
"""Generate EXP-CODEC-006 specs (stdlib only, deterministic).

spec-detection.yaml  deterministic fault-injection detection arm (tuning small+medium items).
spec.yaml            in-process pack-time cost per verification scope (timing; tuning coverage per protocol 6).
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
REPO_WSL = "/mnt/d/Projects/entrybound/entrybound"
EXP = "EXP-CODEC-006"
BIN = "/root/eb-research/target/harness/release/ebr-pack"
SCOPES = [("status-quo", "status-quo"), ("transformed", "transformed"), ("all", "all"),
          ("sampled-q64", "sampled:0.015625"), ("sampled-q16", "sampled:0.0625"), ("sampled-q4", "sampled:0.25"),
          ("post-write", "post-write")]
PROFILES = ["fast", "balanced", "dense", "extreme"]
FAULTS = ["FM1", "FM2", "FM3", "FM4", "FM5"]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def items(tiers: tuple[str, ...]) -> list[str]:
    m = json.loads((REPO / "research/corpus/manifest.json").read_text(encoding="utf-8"))
    return sorted(i["item_id"] for i in m["items"] if i["split"] == "tuning" and i["scale"] in tiers)


def detection() -> str:
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}-detection",
        "status: pre-registration-draft (gate G-A pending)",
        f"notes: {q('Generated by make_specs.py. --inject-fault/--verify-scope/--classify-outcome are TOOLING (protocol 7.1). Each candidate = (scope, fault model); 20 seeded injections per (item, profile) inside one invocation; profile loops inside the tool.')}",
        f"question: {q('Which seeded encoder, transform, parameter, plaintext and dictionary faults does each write-time verification scope detect before write or publication, and does any written archive verify as OK with wrong bytes?')}",
        f"hypothesis: {q('H1a of protocol.md section 3: status quo detects no FM1/FM2 at write; verify-all-chunks and post-write-full-verify detect all FM1-FM3; sampled scopes detect at rate q; no scope detects FM4 (negative control). Binary: zero undetected-verified-wrong outcomes (HC-15/HC-02).')}",
        "decision_ids: [DEC-CMP-044, DEC-CMP-043]",
        "candidates:",
    ]
    for sname, sval in SCOPES:
        for fm in FAULTS:
            lines += [f"  - name: {sname}-{fm.lower()}", f"    params: {{scope: {q(sval)}, fault: {fm}}}"]
    lines += [
        "command: >-",
        f"  {BIN} --item-path {{item_path}} --experiment-id {EXP}-detection --env-name wsl-ubuntu",
        "  --profiles fast,balanced,dense,extreme --verify-scope {scope} --inject-fault {fault}",
        "  --fault-seed 20260917 --fault-count 20 --classify-outcome true",
        f"  --fault-models {REPO_WSL}/research/experiments/{EXP}/configs/fault-models.json --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "  item_ids:",
    ] + [f"    - {i}" for i in items(("small", "medium"))] + [
        "metrics:",
        "  - {name: injections, source: stdout_json, key: payload.injections, family: other, direction: none, unit: count}",
        "  - {name: detected_at_write, source: stdout_json, key: payload.detected_at_write, family: other, direction: maximize, unit: count}",
        "  - {name: detected_at_verify, source: stdout_json, key: payload.detected_at_verify, family: other, direction: none, unit: count}",
        "  - {name: undetected_verified_wrong, source: stdout_json, key: payload.undetected_verified_wrong, family: correctness, direction: minimize, unit: count}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.no_fault_roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: outcome_digest_sha256, source: stdout_json, key: payload.outcome_digest_sha256, family: correctness, kind: string}",
        "repetitions: 2",
        "warmups: 0",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        "timing: false",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
        f"  requires: [{BIN}]",
        "  timeout_s: 172800",
        "analysis:",
        "  pairing: item",
        "  report_metrics: [detected_at_write, undetected_verified_wrong]",
    ]
    return "\n".join(lines) + "\n"


def timing(large: bool = False) -> str:
    profiles = ["fast", "balanced"] if large else PROFILES
    tiers = ("large",) if large else ("small", "medium")
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}{'-large' if large else ''}",
        "status: pre-registration-draft (gate G-A pending; timing gated on decision-method 14 items 3 and 4)",
        f"notes: {q('Generated by make_specs.py. Candidates = (scope, profile). Tier coverage per protocol section 6: this spec lists tuning small+medium items for all profiles; spec-large.yaml (derived mechanically: large tier, fast/balanced candidates only) is committed with it before any run. In-process timer around plan+encode+verification into an in-memory sink.')}",
        f"question: {q('What in-process pack wall and CPU time does each write-time verification scope cost per profile?')}",
        f"hypothesis: {q('H1b of protocol.md section 3: verify-all-chunks is distinguishably slower than status quo at fast/balanced and within one band unit at dense/extreme; verify-all-transformed is equivalent at every profile.')}",
        "decision_ids: [DEC-CMP-044, DEC-CMP-043]",
        "candidates:",
    ]
    for sname, sval in SCOPES:
        for p in profiles:
            lines += [f"  - name: {sname}-{p}", f"    params: {{scope: {q(sval)}, profile: {p}}}"]
    lines += [
        "command: >-",
        f"  {BIN} --item-path {{item_path}} --experiment-id {EXP}{'-large' if large else ''} --env-name wsl-ubuntu",
        "  --profile {profile} --verify-scope {scope} --timing-mode in-process --sink memory --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "  item_ids:",
    ] + [f"    - {i}" for i in items(tiers)] + [
        "metrics:",
        "  - {name: input_bytes, source: input, family: size, direction: none, unit: B}",
        "  - {name: encode_wall_s, source: stdout_json, key: payload.timed.pack_wall_s, family: time_wall, direction: minimize, unit: s}",
        "  - {name: encode_cpu_s, source: stdout_json, key: payload.timed.pack_cpu_s, family: time_cpu, direction: minimize, unit: s}",
        "  - {name: verification_wall_s, source: stdout_json, key: payload.timed.verification_wall_s, family: time_wall, direction: minimize, unit: s}",
        "  - {name: artifact_sha256, source: stdout_json, key: payload.archive_sha256, family: correctness, kind: string}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: wall_s, source: resource, family: time_wall, direction: minimize, unit: s}",
        f"repetitions: {20}",
        f"warmups: {1 if large else 2}",
        "record_warmups: true",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        "timing: true",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
        "  cpu_affinity: [2]",
        f"  requires: [{BIN}]",
        "  timeout_s: 21600",
        "guard:",
        "  max_loadavg_1m: 2.0",
        "  max_other_cpu_percent: 3.0",
        "  max_wait_s: 300",
        "analysis:",
        "  baseline: status-quo-balanced",
        "  pairing: item_repetition",
        "  report_metrics: [encode_wall_s, verification_wall_s, roundtrip_mismatches]",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    (HERE / "spec-detection.yaml").write_text(detection(), encoding="utf-8", newline="\n")
    (HERE / "spec.yaml").write_text(timing(), encoding="utf-8", newline="\n")
    (HERE / "spec-large.yaml").write_text(timing(large=True), encoding="utf-8", newline="\n")
    print(json.dumps({"written": ["spec-detection.yaml", "spec.yaml", "spec-large.yaml"]}))


if __name__ == "__main__":
    main()
