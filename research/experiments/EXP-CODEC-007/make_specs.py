#!/usr/bin/env python3
"""Generate EXP-CODEC-007 specs (stdlib only, deterministic).

spec.yaml           benign single-frame-rule census over production archives (tuning; deterministic).
spec-overhead.yaml  STREAM per-frame digest/CRC size and decode CPU overhead (tuning; timing).
spec-refusal.yaml   hostile STREAM frame refusal cost per candidate (generated; timing).
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = "EXP-CODEC-007"
TBIN = "/root/eb-research/target/harness/release"
ABIN = "/root/eb-research/target/harness-alloc/release"
DEC = "decision_ids: [DEC-INT-008]"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def timing_tail(baseline: str, report: list[str], reps: int, requires: str) -> list[str]:
    return [
        f"repetitions: {reps}",
        "warmups: 2",
        "record_warmups: true",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        "timing: true",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
        "  cpu_affinity: [2]",
        f"  requires: [{requires}]",
        "  timeout_s: 21600",
        "guard:",
        "  max_loadavg_1m: 2.0",
        "  max_other_cpu_percent: 3.0",
        "  max_wait_s: 300",
        "analysis:",
        f"  baseline: {baseline}",
        "  pairing: item_repetition",
        "  report_metrics: [" + ", ".join(report) + "]",
    ]


def benign() -> str:
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}",
        "status: pre-registration-draft (gate G-A pending)",
        f"notes: {q('Generated by make_specs.py. Packs each item with the production ebound build (CC-2) and applies the single-frame rule checker (TOOLING) to every stored payload.')}",
        f"question: {q('Would a rule rejecting extra frames, skippable frames and trailing bytes refuse any codec payload production writes today, at any profile and layout?')}",
        f"hypothesis: {q('H1a: benign_false_refusal_fraction = 0 over every payload (binary census).')}",
        DEC,
        "candidates:",
    ]
    for p in ("fast", "balanced", "dense", "extreme"):
        for layout in ("indexed", "stream"):
            lines += [f"  - name: {p}-{layout}", f"    params: {{profile: {p}, layout: {layout}}}"]
    lines += [
        "command: >-",
        "  /root/eb-research/target/production/release/ebound pack {item_path} {scratch}/a.eb --profile {profile} --layout {layout}",
        "  --stream-window auto >/dev/null &&",
        f"  {TBIN}/ebr-codec single-frame-check --archive-path {{scratch}}/a.eb --experiment-id {EXP} --env-name wsl-ubuntu --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: payloads, source: stdout_json, key: payload.payloads, family: other, direction: none, unit: count}",
        "  - {name: refused_payloads, source: stdout_json, key: payload.refused_payloads, family: correctness, direction: minimize, unit: count}",
        "  - {name: benign_false_refusal_fraction, source: stdout_json, key: payload.benign_false_refusal_fraction, family: other, direction: minimize, unit: fraction}",
        "  - {name: archive_sha256, source: path_sha256, path: '{scratch}/a.eb', family: correctness}",
        "repetitions: 2",
        "warmups: 0",
        "seeds: {order: 20260917, bootstrap: 20260917, command: 20260917}",
        "timing: false",
        "order: randomized_blocks",
        "raw_compression: gzip",
        "platform:",
        "  os: [linux]",
        "  arch: [x86_64]",
        "  emulated: false",
        f"  requires: [/root/eb-research/target/production/release/ebound, {TBIN}/ebr-codec]",
        "  timeout_s: 172800",
        "analysis:",
        "  pairing: item",
        "  report_metrics: [refused_payloads, benign_false_refusal_fraction]",
    ]
    return "\n".join(lines) + "\n"


def overhead() -> str:
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}-overhead",
        "status: pre-registration-draft (gate G-A pending; timing gated on decision-method 14 items 3 and 4)",
        f"notes: {q('Generated by make_specs.py. ebr-pack packs STREAM (production planner, --stream-window auto) and computes exact per-frame field size and in-process STREAM decode plus check CPU (TOOLING).')}",
        f"question: {q('What artifact_bytes and STREAM decode CPU would a per-frame stored-bytes digest (BLAKE3 or SHA-256) or CRC32C add on every tuning item at balanced and extreme?')}",
        f"hypothesis: {q('H1b-H1c: a 32-byte digest is equivalent on medium/large items and may exceed the relative band on small many-chunk items; BLAKE3 check CPU stays within one T-05 band unit; SHA-256 costs 1-3 band units on highly compressible items.')}",
        DEC,
        "candidates:",
    ]
    for d in ("none", "crc32c", "blake3", "sha256"):
        for p in ("balanced", "extreme"):
            lines += [f"  - name: {d}-{p}", f"    params: {{digest: {d}, profile: {p}}}"]
    lines += [
        "command: >-",
        f"  {TBIN}/ebr-pack --item-path {{item_path}} --experiment-id {EXP}-overhead --env-name wsl-ubuntu",
        "  --profile {profile} --layout stream --stream-window auto --stream-digest-overhead {digest}",
        "  --timing-mode in-process --sink memory --summary-stdout",
        "shell: bash",
        "corpus:",
        "  manifest: research/corpus/manifest.json",
        "  splits: [tuning]",
        "metrics:",
        "  - {name: input_bytes, source: input, family: size, direction: none, unit: B}",
        "  - {name: artifact_bytes, source: stdout_json, key: payload.artifact_bytes_with_field, family: size, direction: minimize, unit: B}",
        "  - {name: stream_frame_count, source: stdout_json, key: payload.stream_frame_count, family: other, direction: none, unit: count}",
        "  - {name: decode_cpu_s, source: stdout_json, key: payload.timed.stream_decode_plus_check_cpu_s, family: time_cpu, direction: minimize, unit: s}",
        "  - {name: check_cpu_s, source: stdout_json, key: payload.timed.check_cpu_s, family: time_cpu, direction: minimize, unit: s}",
        "  - {name: roundtrip_mismatches, source: stdout_json, key: payload.roundtrip_mismatches, family: correctness, direction: minimize, unit: count}",
        "  - {name: ratio, source: derived, op: ratio, args: [artifact_bytes, input_bytes], family: size, direction: minimize}",
    ]
    lines += timing_tail("none-balanced", ["artifact_bytes", "decode_cpu_s", "check_cpu_s"], 10, f"{TBIN}/ebr-pack")
    return "\n".join(lines) + "\n"


def refusal() -> str:
    lines = [
        "schema: ebr.spec.v1",
        f"experiment_id: {EXP}-refusal",
        "status: pre-registration-draft (gate G-A pending; timing gated on decision-method 14 items 3 and 4)",
        f"notes: {q('Generated by make_specs.py. Items: hostile STREAM archives from gen_stream_hostile.py (seeded; lock file; manifest stream-hostile-manifest.json, split=generated), including F20 bomb items repacked as STREAM. Allocator build for refusal_alloc_peak_bytes.')}",
        f"question: {q('How much CPU, memory and input does a STREAM reader consume before rejecting hostile frames under each DEC-INT-008 candidate, and is every rejection a distinguishable failure?')}",
        f"hypothesis: {q('H1d: status-quo hardened decoders stop within budgets but spend at least one T-05 band unit more refusal CPU than a stored-bytes digest check; CRC32C does not reject crafted frames with valid CRCs; no hostile frame yields OK.')}",
        DEC,
        "candidates:",
    ]
    for c in ("hardened-decoders-and-budgets", "stream-stored-bytes-digest-blake3", "stream-stored-bytes-digest-sha256", "per-frame-crc32c", "enforce-single-frame-no-trailing"):
        lines += [f"  - name: {c}", f"    params: {{cand: {c}}}"]
    lines += [
        "command: >-",
        f"  {ABIN}/ebr-codec stream-refusal --archive-path {{item_path}} --experiment-id {EXP}-refusal",
        "  --env-name wsl-ubuntu --candidate {cand} --summary-stdout",
        "shell: bash",
        "corpus:",
        f"  manifest: research/experiments/{EXP}/stream-hostile-manifest.json",
        "  splits: [generated]",
        "metrics:",
        "  - {name: refusal_cpu_s, source: stdout_json, key: payload.refusal_cpu_s, family: time_cpu, direction: minimize, unit: s}",
        "  - {name: refusal_alloc_peak_bytes, source: stdout_json, key: payload.refusal_alloc_peak_bytes, family: memory_peak, direction: minimize, unit: B}",
        "  - {name: refusal_bytes_read, source: stdout_json, key: payload.refusal_bytes_read, family: size, direction: minimize, unit: B}",
        "  - {name: ok_on_hostile, source: stdout_json, key: payload.ok_on_hostile, family: correctness, direction: minimize, unit: count}",
        "  - {name: outcome_class, source: stdout_json, key: payload.outcome_class, family: correctness, kind: string}",
    ]
    lines += timing_tail("hardened-decoders-and-budgets", ["refusal_cpu_s", "refusal_alloc_peak_bytes", "ok_on_hostile"], 10, f"{ABIN}/ebr-codec")
    return "\n".join(lines) + "\n"


def main() -> None:
    (HERE / "spec.yaml").write_text(benign(), encoding="utf-8", newline="\n")
    (HERE / "spec-overhead.yaml").write_text(overhead(), encoding="utf-8", newline="\n")
    (HERE / "spec-refusal.yaml").write_text(refusal(), encoding="utf-8", newline="\n")
    print(json.dumps({"written": ["spec.yaml", "spec-overhead.yaml", "spec-refusal.yaml"]}))


if __name__ == "__main__":
    main()
